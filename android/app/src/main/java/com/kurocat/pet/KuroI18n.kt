package com.kurocat.pet

import android.content.Context
import java.util.Locale

/**
 * Full 9-locale runtime localization for KuroCat Android, matching the 9 desktop languages:
 * `zh-CN`, `zh-TW`, `en-US`, `ja-JP`, `ko-KR`, `es-ES`, `pt-BR`, `ru-RU`, `de-DE` (+ `auto`).
 */
object KuroI18n {
    data class LangOption(val code: String, val label: String)

    val LANG_OPTIONS = listOf(
        LangOption("auto", "Auto"),
        LangOption("zh-CN", "简体"),
        LangOption("zh-TW", "繁體"),
        LangOption("en-US", "EN"),
        LangOption("ja-JP", "日本語"),
        LangOption("ko-KR", "한국어"),
        LangOption("es-ES", "ES"),
        LangOption("pt-BR", "PT"),
        LangOption("ru-RU", "RU"),
        LangOption("de-DE", "DE"),
    )

    fun resolveLocale(ctx: Context): String {
        val saved = KuroPrefs.getLanguage(ctx)
        if (saved != "auto") return saved
        val loc = Locale.getDefault()
        val lang = loc.language.lowercase(Locale.ROOT)
        val country = loc.country.uppercase(Locale.ROOT)
        val script = loc.script.lowercase(Locale.ROOT)
        return when (lang) {
            "zh" -> if (script == "hant" || country in setOf("TW", "HK", "MO")) "zh-TW" else "zh-CN"
            "ja" -> "ja-JP"
            "ko" -> "ko-KR"
            "es" -> "es-ES"
            "pt" -> "pt-BR"
            "ru" -> "ru-RU"
            "de" -> "de-DE"
            else -> "en-US"
        }
    }

    fun skinName(ctx: Context, id: String): String = t(ctx, "skin.$id")

    fun t(ctx: Context, key: String): String {
        val loc = resolveLocale(ctx)
        return STRINGS[loc]?.get(key)
            ?: STRINGS["en-US"]?.get(key)
            ?: STRINGS["zh-CN"]?.get(key)
            ?: key
    }

