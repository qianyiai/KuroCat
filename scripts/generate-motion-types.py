"""Generate protocol types using the checked-in schema. No third-party modules."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "src-tauri/protocol/motion-2d.schema.json"


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def rust_type(spec):
    if "$ref" in spec:
        return spec["$ref"].rsplit("/", 1)[1]
    kind = spec["type"]
    if kind == "array":
        item = rust_type(spec["items"])
        if spec.get("minItems") == spec.get("maxItems"):
            return f"[{item}; {spec['minItems']}]"
        return f"Vec<{item}>"
    return {"number": "f64", "integer": "u32", "string": "String", "boolean": "bool"}[kind]


def ts_type(spec):
    if "$ref" in spec:
        return spec["$ref"].rsplit("/", 1)[1]
    if "const" in spec:
        return json.dumps(spec["const"])
    if "enum" in spec:
        return " | ".join(json.dumps(v) for v in spec["enum"])
    if spec["type"] == "array":
        item = ts_type(spec["items"])
        if spec.get("minItems") == spec.get("maxItems"):
            return "[" + ", ".join([item] * spec["minItems"]) + "]"
        return f"Array<{item}>"
    return {"number": "number", "integer": "number", "string": "string", "boolean": "boolean"}[spec["type"]]


def generate():
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    definitions = {"Motion2d": schema, **schema["$defs"]}
    rust = ["// Generated by scripts/generate-motion-types.py; edit the schema instead.",
            "use serde::{Deserialize, Serialize};", ""]
    ts = ["// Generated by scripts/generate-motion-types.py; edit the schema instead."]
    for name, spec in definitions.items():
        rust.extend(["#[derive(Debug, Clone, Serialize, Deserialize)]",
                     '#[serde(rename_all = "camelCase", deny_unknown_fields)]', f"pub struct {name} {{"])
        ts.append(f"export interface {name} {{")
        for field, field_spec in spec["properties"].items():
            required = field in spec["required"]
            if not required:
                rust.append('    #[serde(default, skip_serializing_if = "Option::is_none")]')
            kind = rust_type(field_spec)
            rust.append(f"    pub {snake(field)}: {kind if required else f'Option<{kind}>'},")
            ts.append(f"  {field}{'' if required else '?'}: {ts_type(field_spec)};")
        rust.extend(["}", ""])
        ts.extend(["}", ""])
    return {ROOT / "src-tauri/src/motion2d_types.rs": "\n".join(rust) + "\n",
            ROOT / "src/characterMotion2d.ts": "\n".join(ts) + "\n"}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Generated file is stale: {path}")
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
    print("Motion protocol types match schema" if args.check else "Generated motion protocol types")
